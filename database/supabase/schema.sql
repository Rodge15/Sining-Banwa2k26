-- Supabase Postgres schema for Sining Banwa.
-- Run this once in the Supabase SQL editor on an empty project.
-- Do not run it in phpMyAdmin or against the local MySQL database.
-- Running it again does not drop or rewrite existing rows.

CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$;

CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  email VARCHAR(190) NOT NULL,
  phone VARCHAR(30) DEFAULT NULL,
  password_hash VARCHAR(255) NOT NULL,
  role VARCHAR(20) NOT NULL DEFAULT 'customer',
  is_active SMALLINT NOT NULL DEFAULT 1,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT users_role_check CHECK (role IN ('customer', 'admin', 'staff', 'venue')),
  CONSTRAINT users_is_active_check CHECK (is_active IN (0, 1)),
  CONSTRAINT uq_users_email UNIQUE (email)
);

CREATE INDEX IF NOT EXISTS idx_users_role_active ON users (role, is_active);

DROP TRIGGER IF EXISTS users_set_updated_at ON users;
CREATE TRIGGER users_set_updated_at
  BEFORE UPDATE ON users
  FOR EACH ROW
  EXECUTE FUNCTION set_updated_at();

CREATE TABLE IF NOT EXISTS password_reset_tokens (
  user_id BIGINT NOT NULL PRIMARY KEY,
  token_hash CHAR(64) NOT NULL,
  expires_at TIMESTAMP NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_password_reset_tokens_user
    FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_password_reset_tokens_expiry ON password_reset_tokens (expires_at);

CREATE TABLE IF NOT EXISTS events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(160) NOT NULL,
  description TEXT DEFAULT NULL,
  venue VARCHAR(190) NOT NULL,
  starts_at TIMESTAMP NOT NULL,
  poster_filename VARCHAR(40) DEFAULT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'draft',
  created_by BIGINT NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT events_status_check CHECK (status IN ('draft', 'published', 'completed', 'cancelled')),
  CONSTRAINT fk_events_created_by
    FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_events_status_starts_at ON events (status, starts_at);
CREATE INDEX IF NOT EXISTS idx_events_created_by ON events (created_by);

DROP TRIGGER IF EXISTS events_set_updated_at ON events;
CREATE TRIGGER events_set_updated_at
  BEFORE UPDATE ON events
  FOR EACH ROW
  EXECUTE FUNCTION set_updated_at();

CREATE TABLE IF NOT EXISTS event_sections (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id BIGINT NOT NULL,
  name VARCHAR(100) NOT NULL,
  default_price NUMERIC(10,2) NOT NULL DEFAULT 0.00,
  sort_order SMALLINT NOT NULL DEFAULT 0,
  grid_columns SMALLINT DEFAULT NULL,
  grid_rows SMALLINT DEFAULT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT event_sections_grid_columns_check CHECK (grid_columns IS NULL OR grid_columns BETWEEN 0 AND 255),
  CONSTRAINT event_sections_grid_rows_check CHECK (grid_rows IS NULL OR grid_rows BETWEEN 0 AND 255),
  CONSTRAINT uq_event_sections_name UNIQUE (event_id, name),
  CONSTRAINT uq_event_sections_id_event_id UNIQUE (id, event_id),
  CONSTRAINT fk_event_sections_event
    FOREIGN KEY (event_id) REFERENCES events (id) ON DELETE RESTRICT
);

DROP TRIGGER IF EXISTS event_sections_set_updated_at ON event_sections;
CREATE TRIGGER event_sections_set_updated_at
  BEFORE UPDATE ON event_sections
  FOR EACH ROW
  EXECUTE FUNCTION set_updated_at();

CREATE TABLE IF NOT EXISTS event_rows (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id BIGINT NOT NULL,
  section_id BIGINT NOT NULL,
  label VARCHAR(40) NOT NULL,
  sort_order SMALLINT NOT NULL DEFAULT 0,
  CONSTRAINT uq_event_rows_section_label UNIQUE (section_id, label),
  CONSTRAINT uq_event_rows_id_event_id UNIQUE (id, event_id),
  CONSTRAINT fk_event_rows_section
    FOREIGN KEY (section_id, event_id) REFERENCES event_sections (id, event_id) ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS event_seats (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id BIGINT NOT NULL,
  row_id BIGINT NOT NULL,
  label VARCHAR(40) NOT NULL,
  x_position SMALLINT NOT NULL DEFAULT 0,
  y_position SMALLINT NOT NULL DEFAULT 0,
  price_override NUMERIC(10,2) DEFAULT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'available',
  sort_order SMALLINT NOT NULL DEFAULT 0,
  CONSTRAINT event_seats_status_check CHECK (status IN ('available', 'blocked', 'locked', 'reserved', 'sold')),
  CONSTRAINT uq_event_seats_event_label UNIQUE (event_id, label),
  CONSTRAINT fk_event_seats_row
    FOREIGN KEY (row_id, event_id) REFERENCES event_rows (id, event_id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_event_seats_status ON event_seats (row_id, status);

